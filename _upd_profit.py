def main():
    written = []
    for d in DIRS:
        fp = os.path.join(d, NAME)
        if not os.path.isfile(fp):
            print('跳过（不存在）', fp)
            continue
        raw = open(fp, encoding='utf-8').read()
        obj = json.loads(raw)
        data = obj['data']
        before = set(data.keys())
        n_new = 0
        for code, (profit, cost, asof, src, note) in UPD.items():
            if code not in data:
                print('  ! 快照缺少品种', code)
                continue
            rec = data[code]
            if rec.get('profit') != profit:
                n_new += 1
            rec['profit'] = profit
            if cost != K:
                rec['cost'] = cost
            rec['asof'] = asof
            rec['src'] = src
            rec['note'] = note
        assert set(data.keys()) == before, '品种集合发生了变化！'
        obj['asof'] = ASOF
        obj['count'] = len(data)
        # 备份
        bak = fp + '.bak'
        shutil.copy2(fp, bak)
        with open(fp, 'w', encoding='utf-8') as f:
            json.dump(obj, f, ensure_ascii=False, indent=1)
            f.write('\n')
        json.load(open(fp, encoding='utf-8'))  # 校验
        written.append((fp, len(data), n_new))
    for fp, n, ch in written:
        print(f'✓ {fp} · {n} 个品种 · 档位变动 {ch} 处（备份 .bak）')


if __name__ == '__main__':
    main()
